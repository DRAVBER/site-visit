/** icon registry for data-driven categories (data/categories.json → icon) */
export const CATEGORY_ICONS: Record<string, LucideIcon> = {
  globe: Globe,
  monitor: Monitor,
  terminal: Terminal,
  sparkles: Sparkles,
};

/**
 * Renders a category icon; unknown names fall back to a folder so a newly
 * added category (config-only) never breaks the UI.
 */
export function CategoryGlyph({
  name,
  className,
}: {
  name?: string;
  className?: string;
}) {
  const Icon = (name && CATEGORY_ICONS[name]) || Folder;
  return <Icon className={className} aria-hidden="true" />;
}
